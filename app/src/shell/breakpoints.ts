/**
 * @ai-context 全站断点的**单一真源**（规格 §1 决策 16「断点 1024/1100/1180」+ §6.2 阈值口径）。
 *
 * Why 收成一处：今日同一个「窄窗自动折叠」概念在 6 个调用点写成了 3 个不同的数
 *   （860 出现 4 次、700 一次、1100 一次），且**没有一处能从数字反推出理由**。
 *   规格 §6.2 给了推导规则：「按折叠后正文是否仍 ≥520px 反推」——
 *   三列页 1024 · 两列页 1100 · 大纲列 1280。本模块把规则与数字放在一起。
 *
 * 口径：这些值是 `window.innerWidth` 的**下限**（视口宽 ≥ 该值时不折叠）；
 *   比较一律用严格小于（见 useColumnLayout: `window.innerWidth < autoFoldBelow` ⇒ 折叠）。
 *   ⇒ 写下 1100 的含义是「1099 折叠、1100 不折叠」。
 *
 * 副作用：无（纯数据）。
 * 边界：本模块只提供**档位值**，不含档位算术；顶栏的档位判定在 T7 的 TopBar 里，
 *   但它必须引用本模块的 `nav` / `navFull` / `navActionsFull`，不得另写数字。
 */
export const BREAKPOINTS = {
  /** 导航下限 = 最小窗宽（规格 §6.1「<1024 由最小窗兜底」） */
  nav: 1024,
  /** 导航满档：≥1180 图标+文字，1024–1180 仅图标（规格 §6.1 溢出两级） */
  navFull: 1180,
  /**
   * 顶栏**右侧动作簇**（⌘K / 对话面板 / ⚙）恢复文字的下限。
   *
   * Why 需要第三个档位（规格没有此档，是实测逼出来的 —— **跨任务依赖：本常量服务批 3 T7 的
   *   顶栏右簇，不是列契约的需求**；控制方 2026-09-12 裁决 A7 后由 T8 的提交先行落库，
   *   否则 T7 的提交树不编译）：批 3 T7 用 CDP 真组件探针实测（**读数出自 T7 报告**）——
   *   满档（≥1180 图标+文字）含最宽采集徽标态需 **1353.8 px** ⇒ **连默认窗 1280 都装不下**
   *   （溢出 16.8，把 ⚙ 推出右缘）；收掉右簇文字后最坏 **1145.94 ≤ 1165**（1180 视口的内容宽）；
   *   到 1400 时三份文字都装得下（**1263.8 ≤ 1400**）⇒ 本档位 = 右簇文字重新出现的地方。
   *   `navFull = 1180` 是规格数字、由 `breakpoints.test.ts` 冻结 ⇒ 只能让内容缩小去装 1180。
   *
   * 与规格「约 1070px」的关系 —— **推断，不是实测**（两种解释给出同一修法，故不据此断言）：
   *   解释甲（控制方复核提出）：规格那个数**假设了右簇不带文字**——收掉右簇文字 + 收
   *   padding/gap 后预测 **1073.94**，与 1070 只差 3.94 px；解释乙：规格漏算 9 个图标
   *   ≈ +234 px。**两者都未经直接验证**，引用时不得写成已证实的事实。
   */
  navActionsFull: 1400,
  /** 两列页的自动折叠阈值（课堂源列 / 会话列表 / 体系左列 / 目标左列 / AI 侧栏） */
  twoCol: 1100,
  /** 三列页的自动折叠阈值（笔记组列 + 列表列） */
  threeCol: 1024,
  /** 大纲列（笔记第三列）：最晚折叠（规格 §6.2「大纲列 1280」） */
  outlineCol: 1280,
} as const;

export type BreakpointKind = keyof typeof BREAKPOINTS;

/** 取阈值的唯一入口（写 `BREAKPOINTS.twoCol` 也可，但走函数便于将来加权/改写） */
export function breakpointFor(kind: BreakpointKind): number {
  return BREAKPOINTS[kind];
}
